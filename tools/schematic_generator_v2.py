class KiCadSchematicBuilder:
    """Builds valid KiCad 10.x S-expression schematics"""
    
    # Standard symbol library mappings (KiCad 10)
    SYMBOL_LIBS = {
        'R': 'Device:R',
        'C': 'Device:C',
        'D': 'Device:D',
        'U': 'Device:IC_DIP',
        'Q': 'Device:Q_NMOS',
        'J': 'Connector_Generic:Conn_01x02',
        'L': 'Device:L',
        'SW': 'Switch:SW_Push',
        'U1': 'MCU_Microchip_PIC16:PIC16F18855-I/SP',  # KiCad 10 MCU library
        'U2': 'Regulator_Linear:L7805_TO220',
        'U3': 'Amplifier_Operational:LM339',
    }
    
    def __init__(self, spec: dict, project_name: str = "circuit"):
        self.spec = spec
        self.project_name = project_name
        self.components = []
        self.nets = {}
        self.symbols_used = set()
        self.uuid_map = {}
        self._load_components()
        self._load_nets()
    
    def _load_components(self):
        """Parse components from spec"""
        for ref, data in self.spec.get('instances', {}).items():
            self.components.append({
                'ref': ref,
                'part': data.get('part', 'Device:R'),
                'value': data.get('value', '1k'),
                'x': 0.0,  # Will be assigned
                'y': 0.0,
                'uuid': str(uuid.uuid4()),
            })
            self.symbols_used.add(data.get('part', 'Device:R'))
    
    def _load_nets(self):
        """Parse nets from spec"""
        for net_data in self.spec.get('connections', []):
            net_name = net_data.get('net', 'unnamed')
            endpoints = net_data.get('endpoints', [])
            self.nets[net_name] = endpoints
    
    def _assign_layout(self):
        """Assign grid-based positions"""
        logger.info("Assigning component positions...")
        
        # Categorize components
        mcu_comps = [c for c in self.components if 'MCU' in c['part'] or c['ref'].startswith('U')]
        ic_comps = [c for c in self.components if c['ref'].startswith('U') and c not in mcu_comps]
        connectors = [c for c in self.components if c['ref'].startswith('J')]
        resistors = [c for c in self.components if c['ref'].startswith('R')]
        caps = [c for c in self.components if c['ref'].startswith('C')]
        diodes = [c for c in self.components if c['ref'].startswith('D')]
        others = [c for c in self.components if c not in mcu_comps + ic_comps + connectors + resistors + caps + diodes]
        
        x_pos, y_pos = 50, 50
        
        # Place MCU center
        for comp in mcu_comps:
            comp['x'] = 100
            comp['y'] = y_pos
            y_pos += 30
        
        # Place ICs
        y_pos = 50
        x_ic = 140
        for comp in ic_comps:
            comp['x'] = x_ic
            comp['y'] = y_pos
            y_pos += 30
        
        # Place connectors on left
        y_pos = 50
        for comp in connectors:
            comp['x'] = 20
            comp['y'] = y_pos
            y_pos += 25
        
        # Place passives right side
        x_pass = 160
        y_pass = 50
        for i, comp in enumerate(resistors + caps + diodes):
            if i > 0 and i % 8 == 0:
                x_pass += 30
                y_pass = 50
            comp['x'] = x_pass
            comp['y'] = y_pass
            y_pass += 20
    
    def generate_sexp(self) -> str:
        """Generate complete KiCad 9.x schematic S-expression"""
        self._assign_layout()
        
        lines = [
            '(kicad_sch (version 20240108)',  # KiCad 9.x format
            f'  (uuid "{uuid.uuid4()}")',
            '',
            '  (paper "A4" "landscape")',
            '',
            '  (title_block',
            f'    (title "{self.spec.get("project", {}).get("name", self.project_name)}")',
            f'    (date "{datetime.now().strftime("%Y-%m-%d")}")',
            f'    (rev "")',
            f'    (comment 1 "Auto-generated by schematic_generator")',
            '  )',
            '',
            '  (lib_symbols',
            '    ; Symbols are loaded from KiCad\'s built-in libraries',
            '  )',
            '',
        ]
        
        # Add all components as sheet instances
        for comp in self.components:
            lines.extend(self._generate_symbol(comp))
        
        # Add wires connecting the nets
        for net_name, endpoints in self.nets.items():
            if len(endpoints) > 1:
                lines.extend(self._generate_wires_for_net(net_name, endpoints))
        
        # Add junction points and labels
        for net_name, endpoints in self.nets.items():
            if len(endpoints) > 0:
                lines.extend(self._generate_net_label(net_name, endpoints))
        
        lines.append(')')
        
        return '\n'.join(lines)
    
    def _generate_symbol(self, comp: dict) -> List[str]:
        """Generate S-expression for a symbol instance"""
        part = comp['part']
        ref = comp['ref']
        value = comp['value']
        x, y = comp['x'], comp['y']
        uuid_str = comp['uuid']
        
        lines = [
            f'  (symbol (lib_id "{part}") (at {x} {y} 0)',
            f'    (uuid "{uuid_str}")',
            f'    (property "Reference" "{ref}" (at {x} {y - 2} 0)',
            '      (effects (font (size 1.27 1.27) (thickness 0.15)) hide)',
            '    )',
            f'    (property "Value" "{value}" (at {x} {y + 2} 0)',
            '      (effects (font (size 1.27 1.27) (thickness 0.15)) hide)',
            '    )',
            '    (pin "1" (uuid "00000000-0000-0000-0000-000000000000"))',
            '  )',
            '',
        ]
        
        return lines
    
    def _generate_wires_for_net(self, net_name: str, endpoints: List[str]) -> List[str]:
        """Generate wires connecting all endpoints in a net"""
        lines = []
        
        # Simple strategy: chain components in the net
        # Extract positions from component references
        positions = []
        for endpoint in endpoints:
            if endpoint in ['GND', '+5V', '+12V']:
                continue  # Skip power/ground labels
            
            parts = endpoint.split('.')
            if len(parts) == 2:
                ref = parts[0]
                for comp in self.components:
                    if comp['ref'] == ref:
                        positions.append((comp['x'], comp['y'], endpoint))
                        break
        
        # Connect endpoints with wires
        for i in range(len(positions) - 1):
            x1, y1, label1 = positions[i]
            x2, y2, label2 = positions[i + 1]
            
            lines.append(f'  (wire (pts (xy {x1} {y1}) (xy {x2} {y2}))')
            lines.append(f'    (stroke (width 0.254) (type solid))')
            lines.append(f'    (uuid "{uuid.uuid4()}")')
            lines.append('  )')
        
        return lines
    
    def _generate_net_label(self, net_name: str, endpoints: List[str]) -> List[str]:
        """Generate labels for nets"""
        if not endpoints or net_name in ['GND', 'unnamed']:
            return []
        
        # Place label at first endpoint position
        for endpoint in endpoints:
            if '.' in endpoint:
                ref = endpoint.split('.')[0]
                for comp in self.components:
                    if comp['ref'] == ref:
                        x, y = comp['x'] + 5, comp['y']
                        return [
                            f'  (global_label "{net_name}" (shape passive)',
                            f'    (at {x} {y} 0)',
                            f'    (effects (font (size 1.27 1.27) (thickness 0.15)) (justify left))',
                            f'    (uuid "{uuid.uuid4()}")',
                            '  )',
                            '',
                        ]
        
        return []


class KiCadSchematicValidator:
    """Validates schematics using kicad-cli"""
    
    def __init__(self, kicad_cli_path: Optional[str] = None):
        if kicad_cli_path:
            self.kicad_cli = Path(kicad_cli_path)
        else:
            # Search common locations
            candidates = [
                Path("C:/Program Files/KiCad/9.0/bin/kicad-cli.exe"),
                Path("C:/Program Files/KiCad/10.0/bin/kicad-cli.exe"),
                Path("/usr/bin/kicad-cli"),
                Path("/opt/KiCad/bin/kicad-cli"),
            ]
            self.kicad_cli = next((p for p in candidates if p.exists()), None)
    
    def run_erc(self, sch_file: Path, output_dir: Path) -> Tuple[bool, List[dict]]:
        """Run ERC check and parse results"""
        if not self.kicad_cli or not self.kicad_cli.exists():
            logger.warning(f"kicad-cli not found, skipping ERC")
            return True, []
        
        logger.info(f"Running ERC on {sch_file.name}...")
        
        try:
            report_file = output_dir / 'erc_report.json'
            result = subprocess.run([
                str(self.kicad_cli), 'sch', 'erc',
                '--output', str(report_file),
                str(sch_file)
            ], capture_output=True, text=True, timeout=60)
            
            violations = self._parse_report(report_file)
            is_clean = len(violations) == 0
            
            status = '✓ PASS' if is_clean else f'✗ FAIL ({len(violations)} violations)'
            logger.info(f"ERC: {status}")
            
            return is_clean, violations
            
        except Exception as e:
            logger.error(f"ERC check error: {e}")
            return False, []
    
    def _parse_report(self, report_file: Path) -> List[dict]:
        """Parse ERC JSON report"""
        if not report_file.exists():
            return []
        
        try:
            with open(report_file) as f:
                data = json.load(f)
            
            violations = []
            for item in data.get('violations', []):
                violations.append({
                    'type': item.get('type', 'unknown'),
                    'message': item.get('message', ''),
                    'severity': item.get('severity', 'warning'),
                })
            
            return violations
        except Exception as e:
            logger.error(f"Failed to parse ERC report: {e}")
            return []


class KiCadSchematicGenerator:
    """Main orchestrator for iterative schematic generation"""
    
    def __init__(self, spec_file: str, output_dir: str = "out"):
        self.spec_file = Path(spec_file)
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(exist_ok=True)
        
        with open(spec_file) as f:
            self.spec = yaml.safe_load(f)
        
        self.project_name = self.spec.get('project', {}).get('name', 'circuit')
        self.validator = KiCadSchematicValidator()
        
        self.iteration = 0
        self.max_iterations = 5
    
    def generate(self) -> Path:
        """Generate schematic file"""
        builder = KiCadSchematicBuilder(self.spec, self.project_name)
        sexp = builder.generate_sexp()
        
        sch_file = self.output_dir / f"{self.project_name}.kicad_sch"
        with open(sch_file, 'w') as f:
            f.write(sexp)
        
        logger.info(f"Generated {sch_file}")
        return sch_file
    
    def run_loop(self):
        """Iterative generation with ERC feedback"""
        logger.info(f"Starting generation loop (max {self.max_iterations} iterations)...")
        
        for self.iteration in range(1, self.max_iterations + 1):
            logger.info(f"\n{'='*70}")
            logger.info(f"Iteration {self.iteration}/{self.max_iterations}")
            logger.info(f"{'='*70}")
            
            sch_file = self.generate()
            is_clean, violations = self.validator.run_erc(sch_file, self.output_dir)
            
            if is_clean:
                logger.info(f"\n{'='*70}")
                logger.info("✓ SCHEMATIC GENERATION COMPLETE - ERC CLEAN")
                logger.info(f"Output: {sch_file}")
                logger.info(f"{'='*70}\n")
                return True
            
            if self.iteration < self.max_iterations:
                logger.info(f"\nApplying fixes and regenerating...")
                # In future: implement intelligent fixing based on violation types
                pass
            else:
                logger.warning(f"\nReached max iterations. Remaining violations:")
                for v in violations[:10]:
                    logger.warning(f"  [{v['severity'].upper()}] {v['type']}: {v['message']}")
        
        return False


def main():
    if len(sys.argv) < 2:
        print("Usage: python schematic_generator.py <spec.yaml> [output_dir]")
        sys.exit(1)
    
    spec_file = sys.argv[1]
    output_dir = sys.argv[2] if len(sys.argv) > 2 else "out"
    
    generator = KiCadSchematicGenerator(spec_file, output_dir)
    success = generator.run_loop()
    
    sys.exit(0 if success else 1)


if __name__ == '__main__':
    main()
